"""Every published fixture rate must say where it came from.

Without this, a fixture priced at the hardcoded 1.4/1.1 fallback is
indistinguishable from one blended 60/30/10 from three fitted models, and
assert_valid_prediction_output cannot detect the difference because a 1X2
triple still sums to 1.

These tests assert against the COMMITTED ``predictions/fpl/xp_gwNN.json`` for
the highest gameweek number present. That artifact is regenerated by a full
pipeline run (``python -m pipeline.run_pipeline``), which this environment
cannot execute — pymc, xgboost and sklearn are absent from the venv. Rather
than assert against known-stale data, both tests are gated behind
PHASE0_VERIFY_ARTIFACTS so CI enforces them after its next daily pipeline run
regenerates the artifact, while local runs (where the venv can't produce a
fresh one anyway) skip cleanly.

The pipeline never rewrites a past gameweek's file: GW1 produces
``xp_gw01.json``, GW2 produces ``xp_gw02.json``, and so on, with earlier
files left untouched. A test pinned to ``xp_gw01.json`` would freeze at
whatever GW1 last produced and verify nothing about the current run once the
season moves on, so the newest file present is the one that reflects today's
pipeline output and the one these tests must check.
"""
import json
import os
import re
import unittest
from pathlib import Path
from tempfile import TemporaryDirectory
from typing import Optional

REPO = Path(__file__).resolve().parents[2]
ARTIFACT_DIR = REPO / "predictions" / "fpl"

_GW_RE = re.compile(r"^xp_gw(\d+)\.json$")


def latest_xp_artifact(artifact_dir: Path) -> Optional[Path]:
    """Return the ``xp_gwNN.json`` file with the highest NN, or None if absent.

    Selection is by the parsed integer, not lexical order: lexical order
    would rank ``xp_gw10.json`` before ``xp_gw09.json`` (the leading "1"
    sorts below "9" only for equal-length strings, and would still break the
    moment a gameweek reaches three digits), so the number embedded in each
    filename is parsed and compared numerically.
    """
    best_gw: Optional[int] = None
    best_path: Optional[Path] = None
    for path in artifact_dir.glob("xp_gw*.json"):
        match = _GW_RE.match(path.name)
        if not match:
            continue
        gw = int(match.group(1))
        if best_gw is None or gw > best_gw:
            best_gw = gw
            best_path = path
    return best_path


class LatestArtifactSelection(unittest.TestCase):
    """Selection logic only — never touches the real predictions/ tree."""

    def test_selects_highest_gameweek_not_lexical_order(self):
        with TemporaryDirectory() as tmp:
            tmp_dir = Path(tmp)
            for name in ("xp_gw01.json", "xp_gw02.json", "xp_gw10.json"):
                (tmp_dir / name).write_text("{}", encoding="utf-8")
            selected = latest_xp_artifact(tmp_dir)
            self.assertEqual(selected, tmp_dir / "xp_gw10.json")

    def test_returns_none_when_no_artifact_present(self):
        with TemporaryDirectory() as tmp:
            self.assertIsNone(latest_xp_artifact(Path(tmp)))


class PublishedRatesDeclareTheirSource(unittest.TestCase):
    @unittest.skipUnless(
        os.environ.get("PHASE0_VERIFY_ARTIFACTS"),
        "requires a fresh pipeline run; CI enforces this",
    )
    def test_every_fixture_declares_a_rate_source(self):
        artifact = latest_xp_artifact(ARTIFACT_DIR)
        if artifact is None:
            self.skipTest(f"no xp_gw*.json present in {ARTIFACT_DIR}")
        payload = json.loads(artifact.read_text(encoding="utf-8"))
        fixtures = payload.get("fixtures") or []
        self.assertTrue(fixtures, f"{artifact.name} has no fixtures")
        missing = [
            f"{f.get('home_team')} v {f.get('away_team')}"
            for f in fixtures if not f.get("rate_source")
        ]
        self.assertEqual(
            missing, [],
            f"{artifact.name}: fixtures published with a null rate_source — "
            "the FPL layer is reading unanchored rates: " + ", ".join(missing),
        )

    @unittest.skipUnless(
        os.environ.get("PHASE0_VERIFY_ARTIFACTS"),
        "requires a fresh pipeline run; CI enforces this",
    )
    def test_gameweek_one_is_market_anchored(self):
        artifact = latest_xp_artifact(ARTIFACT_DIR)
        if artifact is None:
            self.skipTest(f"no xp_gw*.json present in {ARTIFACT_DIR}")
        payload = json.loads(artifact.read_text(encoding="utf-8"))
        sources = {f.get("rate_source") for f in payload.get("fixtures") or []}
        self.assertIn(
            "market_blend", sources,
            f"{artifact.name}: no fixture is market-anchored; the odds blend "
            "is being discarded",
        )


if __name__ == "__main__":
    unittest.main()
