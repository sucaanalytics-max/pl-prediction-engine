"""
Stage two: score the MILP's shortlist on the objective that actually matters.

The MILP maximises a linear surrogate, because that is what a MILP can do. Three
things it necessarily gets wrong, all of which this module gets right:

* **Autosub is a cascade, not a weight.** A bench player is worth something only
  when a starter fails AND the resulting formation is still legal. The MILP
  prices him at a flat 0.115 regardless. Here the substitution is resolved per
  draw, so a fourth defender behind a back three is correctly worth less than
  the same player behind a back four.
* **The armband can move.** If the captain does not appear the vice inherits it.
  A linear vice weight cannot express a conditional.
* **Clean sheets are shared.** Two defenders from one club keep a clean sheet in
  the same draws, so a squad stacked on one defence has a fatter tail than one
  spread across four. The mean is identical; the distribution is not, and the
  weekly objective is defined on the distribution.

Every plan is scored on the SAME draws. That pairing is not an optimisation —
the between-draw variance dwarfs the between-plan difference, so unpaired
comparison would rank plans by simulation noise. With common random numbers the
noise cancels in the difference.

The plan's own advice on the winner's curse applies to the output of this
module: the shortlist was generated by maximising over a surrogate, so
re-scoring it here on the SAME draws still carries selection bias. Where an
honest number is needed, pass draws the MILP never saw.
"""
from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import Any, Dict, List, Mapping, Optional, Sequence

import numpy as np

from pipeline.decide.milp import Plan, ft_value
from pipeline.fpl.autosub import score_squad
from pipeline.fpl.rules import Rules, load_rules

logger = logging.getLogger(__name__)

# Thresholds the weekly objective keys on. p_ge_10 is the load-bearing one: it
# is the best-calibrated tail in the current simulator (0.0459 predicted against
# 0.0463 realised) and is the scale at which a gameweek is actually won.
TAIL_THRESHOLDS = (40, 50, 60, 70, 80, 90)


@dataclass
class PlanEvaluation:
    """One plan's full outcome distribution under the joint simulator."""

    plan: Plan
    n_draws: int
    # Simulated points only: autosub and captaincy resolved, hit already
    # subtracted. This is a realisable score, so it is what gets reported.
    mean_points: float
    sd_points: float
    quantiles: Dict[str, float] = field(default_factory=dict)
    tails: Dict[str, float] = field(default_factory=dict)
    # Decision value: mean points plus the value of transfers left banked. Plans
    # are RANKED on this and REPORTED on mean_points, because banked-transfer
    # value is a modelling assumption and points are not.
    objective: float = 0.0
    autosub_rate: float = 0.0
    vice_rate: float = 0.0

    def as_dict(self) -> Dict[str, Any]:
        return {
            "plan": self.plan.as_dict(),
            "n_draws": self.n_draws,
            "mean_points": round(self.mean_points, 4),
            "sd_points": round(self.sd_points, 4),
            "objective": round(self.objective, 4),
            "quantiles": {k: round(v, 3) for k, v in self.quantiles.items()},
            "tails": {k: round(v, 5) for k, v in self.tails.items()},
            "autosub_rate": round(self.autosub_rate, 4),
            "vice_rate": round(self.vice_rate, 4),
        }


def order_bench(
    plan: Plan, positions: Mapping[int, str], xp: Mapping[int, float]
) -> List[int]:
    """
    Bench in FPL priority order: reserve keeper first, then outfield by value.

    The MILP has no bench-order variable, so this is a genuine decision made
    here rather than a formatting step. Descending expected points is the
    standard and near-optimal choice: the first bench slot is tried first, so
    the most valuable substitute should occupy it.

    It is not exactly optimal — a player who unlocks more legal formations can
    be worth more from an earlier slot than a marginally better one who does
    not. That interaction is small and the simulator prices whatever order it
    is handed, so the ordering is honest about being a heuristic.
    """
    bench = [p for p in plan.squad if p not in set(plan.xi)]
    keepers = [p for p in bench if positions[p] == "GKP"]
    outfield = [p for p in bench if positions[p] != "GKP"]
    outfield.sort(key=lambda p: (-xp.get(p, 0.0), p))
    return keepers + outfield


def evaluate_plan(
    plan: Plan,
    draws: Any,
    positions: Mapping[int, str],
    rules: Optional[Rules] = None,
    xp: Optional[Mapping[int, float]] = None,
    chip: Optional[str] = None,
) -> PlanEvaluation:
    """
    Score one plan across every draw, resolving autosub and captaincy exactly.

    ``draws`` is a :class:`GameweekDraws`: an ``element_ids`` list plus aligned
    ``points`` and ``minutes`` matrices of shape ``(n_draws, n_players)``.
    """
    rules = rules or load_rules()

    missing = [p for p in plan.squad if p not in draws.element_ids]
    if missing:
        # Treating an absent player as a zero would quietly convert him into a
        # blank, and the plan would be scored as though a real footballer were
        # guaranteed to return nothing.
        raise KeyError(f"plan contains players absent from the draws: {sorted(missing)}")

    column = {int(e): i for i, e in enumerate(draws.element_ids)}
    xi = list(plan.xi)
    bench = order_bench(plan, positions, xp or {})
    squad = xi + bench

    xi_cols = np.array([column[p] for p in xi])
    squad_cols = np.array([column[p] for p in squad])
    captain_col = column[plan.captain]

    points = np.asarray(draws.points)
    minutes = np.asarray(draws.minutes)
    n_draws = int(points.shape[0])

    # Appearance keyed on minutes alone. The rules define an appearance as time
    # on the pitch OR a card, so a zero-minute booking is an appearance the
    # simulator cannot represent -- it draws no card matrix. The case is rare
    # (a benched player booked) and its only effect is that such a player may be
    # substituted here when FPL would not have substituted him.
    appeared = minutes[:, squad_cols] >= 1
    all_xi_played = appeared[:, : len(xi)].all(axis=1)

    transfer_cost = 4 * plan.hits
    totals = np.empty(n_draws, dtype=np.float64)

    # Fast path: when all eleven starters appear there is no substitution and no
    # captaincy fallback, so the score is a plain sum. This is the same
    # arithmetic score_squad would perform, asserted draw for draw by a test. It
    # matters because the fast path covers most draws and the slow path is a
    # Python loop.
    #
    # It is CORRECT ONLY WITH NO CHIP, and that is why a chip disables it
    # entirely. Bench Boost counts all fifteen and Triple Captain multiplies by
    # three, neither of which this sum expresses; applying it to some draws and
    # the resolver to others would score one squad under two different rulebooks
    # and silently understate a Bench Boost week by most of its bench. Chips are
    # played about four times a season, so routing them through the exact
    # resolver costs nothing that matters.
    fast = np.array([], dtype=int) if chip else np.where(all_xi_played)[0]
    if fast.size:
        totals[fast] = (
            points[np.ix_(fast, xi_cols)].sum(axis=1)
            + points[fast, captain_col]
            - transfer_cost
        )

    n_autosub = 0
    n_vice = 0
    slow = np.setdiff1d(np.arange(n_draws), fast, assume_unique=False)
    for d in slow:
        played = {p: bool(appeared[d, i]) for i, p in enumerate(squad)}
        row = {p: int(points[d, column[p]]) for p in squad}
        score = score_squad(
            xi, bench, plan.captain, plan.vice, positions, row, played,
            rules=rules, chip=chip, transfer_cost=transfer_cost,
        )
        totals[d] = score.total
        if score.resolution.substitutions:
            n_autosub += 1
        if score.resolution.vice_used:
            n_vice += 1

    banked = ft_value(plan.free_transfers_banked)
    return PlanEvaluation(
        plan=plan,
        n_draws=n_draws,
        mean_points=float(totals.mean()),
        sd_points=float(totals.std(ddof=1)) if n_draws > 1 else 0.0,
        quantiles={
            f"q{int(q * 100)}": float(np.quantile(totals, q))
            for q in (0.10, 0.25, 0.50, 0.75, 0.90, 0.99)
        },
        tails={
            f"p_ge_{t}": float((totals >= t).mean()) for t in TAIL_THRESHOLDS
        },
        objective=float(totals.mean() + banked),
        autosub_rate=n_autosub / n_draws if n_draws else 0.0,
        vice_rate=n_vice / n_draws if n_draws else 0.0,
    )


def adjudicate(
    plans: Sequence[Plan],
    draws: Any,
    positions: Mapping[int, str],
    rules: Optional[Rules] = None,
    xp: Optional[Mapping[int, float]] = None,
    objective: str = "season",
    tail_threshold: int = 70,
    chip: Optional[str] = None,
) -> List[PlanEvaluation]:
    """
    Rank the MILP's shortlist on the true objective. Best first.

    ``objective`` selects which functional decides the order, and this is where
    the two mandates diverge:

    * ``"season"`` ranks on expected points. Variance is a cost, so a squad
      spread across many defences is preferred to an equivalent-mean stack.
    * ``"weekly"`` ranks on ``P(score >= tail_threshold)``. Variance is an asset:
      winning a gameweek prize needs a right-tail outcome, and correlated
      players are how a tail is reached. The SAME draws produce both answers,
      which is only possible because clean sheets are drawn jointly.

    A reordering between the two is the expected result, not a bug. If season
    and weekly always agreed, the correlation structure would not be doing
    anything and one of the two teams would be redundant.
    """
    if objective not in ("season", "weekly"):
        raise ValueError(f"unknown objective {objective!r}; use 'season' or 'weekly'")
    if not plans:
        raise ValueError("no plans to adjudicate")
    if objective == "weekly" and tail_threshold not in TAIL_THRESHOLDS:
        # Refuse rather than default to zero. A missing tail silently becoming
        # 0.0 for every plan would make the weekly ranking collapse to the
        # season ranking, and the artifact would still claim it was a tail
        # decision.
        raise ValueError(
            f"tail_threshold {tail_threshold} is not computed; "
            f"choose one of {list(TAIL_THRESHOLDS)}"
        )

    key = f"p_ge_{tail_threshold}"
    evaluations = [
        evaluate_plan(p, draws, positions, rules=rules, xp=xp, chip=chip)
        for p in plans
    ]

    if objective == "season":
        evaluations.sort(key=lambda e: -e.objective)
    else:
        evaluations.sort(key=lambda e: (-e.tails.get(key, 0.0), -e.objective))

    if len(evaluations) > 1:
        winner, runner_up = evaluations[0], evaluations[1]
        logger.info(
            "adjudicated %d plans on %s: winner %.3f pts (%s) vs runner-up %.3f",
            len(evaluations), objective, winner.mean_points,
            key if objective == "weekly" else "mean", runner_up.mean_points,
        )
    return evaluations


def reranked(milp_order: Sequence[Plan], adjudicated: Sequence[PlanEvaluation]) -> bool:
    """
    Did the simulator disagree with the MILP about which plan is best?

    Worth recording every week. If it never disagrees the second stage is
    costing time for nothing; if it disagrees constantly the linear surrogate
    needs work. Either finding is actionable, and neither is visible without
    this comparison.
    """
    if not milp_order or not adjudicated:
        return False
    return sorted(milp_order[0].squad) != sorted(adjudicated[0].plan.squad)
